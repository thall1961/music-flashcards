// Helper to format verb conjugations
function conj(
  infinitive: string,
  forms: [string, string, string, string, string, string]
): string {
  return `${infinitive}\n\nio ${forms[0]}\ntu ${forms[1]}\nlui/lei ${forms[2]}\nnoi ${forms[3]}\nvoi ${forms[4]}\nloro ${forms[5]}`;
}

function pastConj(
  infinitive: string,
  forms: [string, string, string, string, string, string]
): string {
  return `${infinitive}\n(passato prossimo)\n\nio ${forms[0]}\ntu ${forms[1]}\nlui/lei ${forms[2]}\nnoi ${forms[3]}\nvoi ${forms[4]}\nloro ${forms[5]}`;
}

// Regular -are past with avere
function arePast(infinitive: string, participle: string): string {
  return pastConj(infinitive, [
    `ho ${participle}`,
    `hai ${participle}`,
    `ha ${participle}`,
    `abbiamo ${participle}`,
    `avete ${participle}`,
    `hanno ${participle}`,
  ]);
}

// Past with essere (motion/state verbs)
function esserePast(infinitive: string, participle: string): string {
  return pastConj(infinitive, [
    `sono ${participle}/a`,
    `sei ${participle}/a`,
    `è ${participle}/a`,
    `siamo ${participle.replace(/o$/, "i")}/e`,
    `siete ${participle.replace(/o$/, "i")}/e`,
    `sono ${participle.replace(/o$/, "i")}/e`,
  ]);
}

